/**
 * Exit precedence when multiple diagnostics are present (design §16.2):
 * `70 > 3 > 2 > 4 > 5 > 6 > 1`. A handler/context may preserve only `causeCode`,
 * never remap a primary code by command or environment.
 */
export const EXIT_PRECEDENCE: ReadonlyArray<CliExitCode> = [70, 3, 2, 4, 5, 6, 1];

/** Resolve the dominant exit code across a set of error codes. */
export function resolveExitCode(
  codes: ReadonlyArray<ExecutableAssetErrorCode>,
): CliExitCode {
  const exits = new Set(codes.map((c) => ERROR_CODE_TO_EXIT[c]));
  for (const candidate of EXIT_PRECEDENCE) {
    if (exits.has(candidate)) {
      return candidate;
    }
  }
  return 1;
}
