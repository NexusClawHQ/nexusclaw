const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, zh };

/** Test seam: the full dictionaries, for zh/en key-parity assertions. */
export const testingDictionaries = dictionaries;

export type Translator = (
  key: MessageKey,
  params?: Record<string, string | number>,
) => string;

export function createTranslator(lang: Lang): Translator {
  const dict = dictionaries[lang];
  return (key, params) => {
    let text: string = dict[key] ?? key;
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.replaceAll(`{${name}}`, String(value));
      }
    }
    return text;
  };
}

export function detectLang(): Lang {
  if (typeof navigator === 'undefined') return 'en';
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}
